#include "libft.h"

void	*ft_memset(void *s, int c, t_size_t n)
{
	t_size_t	i;

	i = 0;
	while (i < n)
	{
		((t_byte *)s)[i] = (t_byte) c;
		i++;
	}
	return (s);
}
